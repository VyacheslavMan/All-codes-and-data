def create_lagged_features(series, n_lags, n_steps):
    """
    Создание признаков на основе лагов (задержек) временного ряда

    Parameters:
    series (array): временной ряд
    n_lags (int): количество лагов (признаков)
    n_steps (int): количество шагов прогноза (целевых переменных)

    Returns:
    X (array): матрица признаков
    y (array): матрица целевых переменных
    """
    X, y = [], []
    for i in range(n_lags, len(series) - n_steps + 1):
        X.append(series[i - n_lags:i])  # Признаки: n_lags предыдущих значений
        y.append(series[i:i + n_steps])  # Цели: n_steps следующих значений

    return np.array(X), np.array(y)

def xgboost_forecast(series, n_steps, n_lags=10, test_size=0.2, params=None):
    """
    Прогнозирование временного ряда на n шагов вперед с помощью XGBoost

    Parameters:
    series (array): временной ряд
    n_steps (int): количество шагов прогноза
    n_lags (int): количество используемых лагов
    test_size (float): доля данных для теста (0-1)
    params (dict): параметры XGBoost

    Returns:
    forecast (array): прогноз на n_steps шагов
    model: обученная модель XGBoost
    """

    # Параметры XGBoost по умолчанию
    if params is None:
        params = {
            'n_estimators': 100,
            'learning_rate': 0.1,
            'max_depth': 3,
            'subsample': 0.8,
            'colsample_bytree': 0.8,
            'random_state': 42
        }

    # Создание признаков
    X, y = create_lagged_features(series, n_lags, n_steps)

    # Разделение на train/test
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, shuffle=False, random_state=42
    )

    # Обучение модели
    model = xgb.XGBRegressor(**params)
    model.fit(X_train, y_train)

    # Прогноз на последнем окне данных
    last_window = series[-n_lags:]
    forecast = model.predict(last_window.reshape(1, -1))[0]

    return forecast, model, X_test, y_test

def recursive_xgboost_forecast(series, n_steps, n_lags=10, params=None):
    """
    Рекурсивное прогнозирование на n шагов вперед
    (каждый следующий прогноз использует предыдущие прогнозы как признаки)
    """

    if params is None:
        params = {
            'n_estimators': 100,
            'learning_rate': 0.1,
            'max_depth': 3,
            'random_state': 42
        }

    # Создание признаков для обучения (предсказание только на 1 шаг)
    X, y = [], []
    for i in range(n_lags, len(series)):
        X.append(series[i - n_lags:i])
        y.append(series[i])

    X, y = np.array(X), np.array(y)

    # Обучение модели
    model = xgb.XGBRegressor(**params)
    model.fit(X, y)

    # Рекурсивный прогноз
    current_window = series[-n_lags:].copy()
    forecasts = []

    for _ in range(n_steps):
        # Прогноз на 1 шаг
        next_pred = model.predict(current_window.reshape(1, -1))[0]
        forecasts.append(next_pred)

        # Обновление окна для следующего прогноза
        current_window = np.roll(current_window, -1)
        current_window[-1] = next_pred

    return np.array(forecasts), model

def multioutput_xgboost_forecast(series, n_steps, n_lags=10, params=None):
    """
    Многозадачное прогнозирование (одна модель предсказывает все n шагов сразу)
    """

    # Создание признаков и целевых переменных
    X, y = create_lagged_features(series, n_lags, n_steps)

    if params is None:
        params = {
            'n_estimators': 100,
            'learning_rate': 0.1,
            'max_depth': 3,
            'random_state': 42
        }

    # Обучение модели
    model = xgb.XGBRegressor(**params)
    model.fit(X, y)

    # Прогноз на последнем окне
    last_window = series[-n_lags:]
    forecast = model.predict(last_window.reshape(1, -1))[0]

    return forecast, model


def individual_models_forecast(series, n_steps, n_lags=10, params=None):
    """
    Прямое прогнозирование с отдельной моделью для каждого горизонта
    """

    if params is None:
        params = {
            'n_estimators': 100,
            'learning_rate': 0.1,
            'max_depth': 3,
            'random_state': 42
        }

    forecasts = []
    models = []

    # Обучаем отдельную модель для каждого шага прогноза
    for step in range(n_steps):
        # Создаем признаки для конкретного шага
        X, y = [], []
        for i in range(n_lags, len(series) - step):
            X.append(series[i - n_lags:i])
            y.append(series[i + step])

        X, y = np.array(X), np.array(y)

        # Выбор и обучение модели
        model = xgb.XGBRegressor(**params)

        model.fit(X, y)
        models.append(model)

        # Прогноз для этого шага
        last_window = series[-n_lags:]
        pred = model.predict(last_window.reshape(1, -1))[0]
        forecasts.append(pred)

    return np.array(forecasts), models

