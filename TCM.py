    progs_fr.to_csv('tcm-posled_progs_'+str(type_of_model)+'_'+act_name+'.csv', sep=';', encoding='utf-8')
    toch_fr.to_csv('tcm-posled_toch_'+str(type_of_model)+'_'+act_name+'.csv', sep=';', encoding='utf-8')

