def create_sequences(data, n_lags, n_steps):
    """Создание последовательностей для обучения нейросетей"""
    X, y = [], []
    for i in range(n_lags, len(data) - n_steps + 1):
        X.append(data[i - n_lags:i])
        y.append(data[i:i + n_steps])
    return np.array(X), np.array(y)

def create_single_step_sequences(data, n_lags):
    """Создание последовательностей для однократного прогнозирования"""
    X, y = [], []
    for i in range(n_lags, len(data)):
        X.append(data[i - n_lags:i])
        y.append(data[i])
    return np.array(X), np.array(y)

def create_model(model_type, input_shape, n_steps=1, units=50, activator='relu', **kwargs):
    """
    Создание нейросетевой модели по типу с поддержкой разных входных форматов
    """

    # Определяем, является ли вход последовательностью (3D) или вектором (2D)
    is_sequence_input = len(input_shape) == 2 and input_shape[1] == 1

    if model_type == 'dense':
        if is_sequence_input:
            # Для последовательностей сначала сглаживаем
            model = Sequential([
                Flatten(input_shape=input_shape),
                Dense(units, activation=activator),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])
        else:
            model = Sequential([
                Dense(units, activation=activator, input_shape=input_shape),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])

    elif model_type == 'lstm':
        if is_sequence_input:
            # Уже правильная форма для LSTM
            model = Sequential([
                LSTM(units, activation=activator, input_shape=input_shape, return_sequences=False),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])
        else:
            # Нужно преобразовать в последовательность
            model = Sequential([
                Reshape((input_shape[0], 1), input_shape=input_shape),
                LSTM(units, activation=activator, return_sequences=False),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])

    elif model_type == 'gru':
        if is_sequence_input:
            model = Sequential([
                GRU(units, activation=activator, input_shape=input_shape, return_sequences=False),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])
        else:
            model = Sequential([
                Reshape((input_shape[0], 1), input_shape=input_shape),
                GRU(units, activation=activator, return_sequences=False),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])

    elif model_type == 'bilstm':
        if is_sequence_input:
            model = Sequential([
                Bidirectional(LSTM(units, activation=activator, return_sequences=False), input_shape=input_shape),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])
        else:
            model = Sequential([
                Reshape((input_shape[0], 1), input_shape=input_shape),
                Bidirectional(LSTM(units, activation=activator, return_sequences=False)),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])

    elif model_type == 'cnn':
        if is_sequence_input:
            model = Sequential([
                Conv1D(filters=64, kernel_size=3, activation=activator, input_shape=input_shape),
                MaxPooling1D(pool_size=2),
                Conv1D(filters=32, kernel_size=3, activation=activator),
                Flatten(),
                Dense(units, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])
        else:
            model = Sequential([
                Reshape((input_shape[0], 1), input_shape=input_shape),
                Conv1D(filters=64, kernel_size=3, activation=activator),
                MaxPooling1D(pool_size=2),
                Conv1D(filters=32, kernel_size=3, activation=activator),
                Flatten(),
                Dense(units, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])

    elif model_type == 'cnn_lstm':
        if is_sequence_input:
            model = Sequential([
                Conv1D(filters=64, kernel_size=3, activation=activator, input_shape=input_shape),
                MaxPooling1D(pool_size=2),
                LSTM(units, activation=activator, return_sequences=False),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])
        else:
            model = Sequential([
                Reshape((input_shape[0], 1), input_shape=input_shape),
                Conv1D(filters=64, kernel_size=3, activation=activator),
                MaxPooling1D(pool_size=2),
                LSTM(units, activation=activator, return_sequences=False),
                Dropout(0.2),
                Dense(units//2, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])

    elif model_type == 'stacked_lstm':
        if is_sequence_input:
            model = Sequential([
                LSTM(units, activation=activator, input_shape=input_shape, return_sequences=True),
                Dropout(0.2),
                LSTM(units//2, activation=activator, return_sequences=False),
                Dropout(0.2),
                Dense(units//4, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])
        else:
            model = Sequential([
                Reshape((input_shape[0], 1), input_shape=input_shape),
                LSTM(units, activation=activator, return_sequences=True),
                Dropout(0.2),
                LSTM(units//2, activation=activator, return_sequences=False),
                Dropout(0.2),
                Dense(units//4, activation=activator),
                Dropout(0.2),
                Dense(n_steps)
            ])

    else:
        raise ValueError(f"Неизвестный тип модели: {model_type}")

    return model

def prepare_data_for_model(series, n_lags, n_steps, method, model_type):
    """
    Подготовка данных в правильном формате для конкретной модели и метода
    """
    if method == 'direct':
        X, y = create_sequences(series, n_lags, n_steps)

        # Масштабирование
        scaler_X = StandardScaler()
        scaler_y = StandardScaler()

        X_scaled = scaler_X.fit_transform(X.reshape(-1, n_lags)).reshape(X.shape)
        y_scaled = scaler_y.fit_transform(y.reshape(-1, n_steps)).reshape(y.shape)

        # Определение формы входа
        if model_type in ['lstm', 'gru', 'bilstm', 'cnn', 'cnn_lstm', 'stacked_lstm']:
            input_shape = (n_lags, 1)
            X_reshaped = X_scaled[..., np.newaxis]
        else:
            input_shape = (n_lags,)
            X_reshaped = X_scaled

        return X_reshaped, y_scaled, input_shape, scaler_X, scaler_y

    else:  # recursive или individual
        X, y = create_single_step_sequences(series, n_lags)

        scaler_X = StandardScaler()
        scaler_y = StandardScaler()

        X_scaled = scaler_X.fit_transform(X)
        y_scaled = scaler_y.fit_transform(y.reshape(-1, 1)).flatten()

        # Для sequential моделей преобразуем в 3D
        if model_type in ['lstm', 'gru', 'bilstm', 'cnn', 'cnn_lstm', 'stacked_lstm']:
            input_shape = (n_lags, 1)
            X_reshaped = X_scaled[..., np.newaxis]
        else:
            input_shape = (n_lags,)
            X_reshaped = X_scaled

        return X_reshaped, y_scaled, input_shape, scaler_X, scaler_y

# 1. МЕТОД: ПРЯМОЙ ВЫХОД (весь горизонт сразу)
def direct_output_nn(series, n_steps, n_lags=20, model_type='lstm',
                    units=50, epochs=100, batch_size=32, activator='relu', losses='mse', **model_kwargs):
    """
    Нейросеть с прямым выходом - предсказывает весь горизонт сразу
    """
    # Подготовка данных
    X, y, input_shape, scaler_X, scaler_y = prepare_data_for_model(
        series, n_lags, n_steps, 'direct', model_type
    )

    # Разделение на train/test
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, shuffle=False, random_state=42
    )

    # Построение модели
    model = create_model(model_type, input_shape, n_steps, units,activator, **model_kwargs)
    model.compile(optimizer=Adam(learning_rate=0.001), loss=losses)

    # Обучение
    early_stop = EarlyStopping(monitor='val_loss', patience=10, restore_best_weights=True)
    history = model.fit(
        X_train, y_train,
        validation_data=(X_test, y_test),
        epochs=epochs,
        batch_size=batch_size,
        callbacks=[early_stop],
        verbose=0
    )

    # Прогноз
    last_window = series[-n_lags:]
    last_window_scaled = scaler_X.transform(last_window.reshape(1, -1))

    # Преобразование в правильную форму для модели
    if model_type in ['lstm', 'gru', 'bilstm', 'cnn', 'cnn_lstm', 'stacked_lstm']:
        last_window_reshaped = last_window_scaled.reshape(1, n_lags, 1)
    else:
        last_window_reshaped = last_window_scaled

    forecast_scaled = model.predict(last_window_reshaped, verbose=0)
    forecast = scaler_y.inverse_transform(forecast_scaled)[0]

    return forecast, model, history

# 2. МЕТОД: РЕКУРСИВНЫЙ ПРОГНОЗ
def recursive_nn_forecast(series, n_steps, n_lags=20, model_type='lstm',
                         units=50, epochs=100, batch_size=32, activator='relu', losses='mse', **model_kwargs):
    """
    Рекурсивное прогнозирование - модель предсказывает по одному шагу
    """
    # Подготовка данных
    X, y, input_shape, scaler_X, scaler_y = prepare_data_for_model(
        series, n_lags, 1, 'recursive', model_type
    )

    # Разделение
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, shuffle=False, random_state=42
    )

    # Модель для однократного прогноза
    model = create_model(model_type, input_shape, 1, units, activator, **model_kwargs)
    model.compile(optimizer=Adam(learning_rate=0.001), loss=losses)

    # Обучение
    early_stop = EarlyStopping(monitor='val_loss', patience=10, restore_best_weights=True)
    history = model.fit(
        X_train, y_train,
        validation_data=(X_test, y_test),
        epochs=epochs,
        batch_size=batch_size,
        callbacks=[early_stop],
        verbose=0
    )

    # Рекурсивный прогноз
    current_window = series[-n_lags:].copy()
    forecasts = []

    for _ in range(n_steps):
        # Масштабирование текущего окна
        current_scaled = scaler_X.transform(current_window.reshape(1, -1))

        # Преобразование в правильную форму для модели
        if model_type in ['lstm', 'gru', 'bilstm', 'cnn', 'cnn_lstm', 'stacked_lstm']:
            current_reshaped = current_scaled.reshape(1, n_lags, 1)
        else:
            current_reshaped = current_scaled

        # Прогноз на один шаг
        pred_scaled = model.predict(current_reshaped, verbose=0)
        if pred_scaled.ndim > 1:
            pred_scaled = pred_scaled[0, 0]
        else:
            pred_scaled = pred_scaled[0]

        pred = scaler_y.inverse_transform([[pred_scaled]])[0, 0]
        forecasts.append(pred)

        # Обновление окна
        current_window = np.roll(current_window, -1)
        current_window[-1] = pred

    return np.array(forecasts), model, history

# 3. МЕТОД: ОТДЕЛЬНАЯ МОДЕЛЬ ДЛЯ КАЖДОЙ ТОЧКИ
def individual_models_nn(series, n_steps, n_lags=20, model_type='lstm',
                        units=50, epochs=100, batch_size=32, activator='relu', losses='mse', **model_kwargs):
    """
    Отдельная нейросеть для каждого горизонта прогноза
    """
    forecasts = []
    models = []
    histories = []

    for step in range(n_steps):
        # Создание данных для конкретного шага
        X, y = [], []
        for i in range(n_lags, len(series) - step):
            X.append(series[i - n_lags:i])
            y.append(series[i + step])

        X, y = np.array(X), np.array(y)

        # Проверка, что достаточно данных
        if len(X) < 10:
            print(f"Недостаточно данных для шага {step+1}. Пропускаем.")
            forecasts.append(np.nan)
            models.append(None)
            histories.append(None)
            continue

        # Масштабирование
        scaler_X = StandardScaler()
        scaler_y = StandardScaler()

        X_scaled = scaler_X.fit_transform(X)
        y_scaled = scaler_y.fit_transform(y.reshape(-1, 1)).flatten()

        # Преобразование в правильную форму для модели
        if model_type in ['lstm', 'gru', 'bilstm', 'cnn', 'cnn_lstm', 'stacked_lstm']:
            input_shape = (n_lags, 1)
            X_reshaped = X_scaled[..., np.newaxis]
        else:
            input_shape = (n_lags,)
            X_reshaped = X_scaled

        # Разделение
        X_train, X_test, y_train, y_test = train_test_split(
            X_reshaped, y_scaled, test_size=0.2, shuffle=False, random_state=42
        )

        # Модель для этого шага
        model = create_model(model_type, input_shape, 1, units, activator, **model_kwargs)
        model.compile(optimizer=Adam(learning_rate=0.001), loss=losses)

        # Обучение
        early_stop = EarlyStopping(monitor='val_loss', patience=10, restore_best_weights=True)
        history = model.fit(
            X_train, y_train,
            validation_data=(X_test, y_test),
            epochs=epochs,
            batch_size=batch_size,
            callbacks=[early_stop],
            verbose=0
        )

        # Прогноз для этого шага
        last_window = series[-n_lags:]
        last_scaled = scaler_X.transform(last_window.reshape(1, -1))

        # Преобразование в правильную форму
        if model_type in ['lstm', 'gru', 'bilstm', 'cnn', 'cnn_lstm', 'stacked_lstm']:
            last_reshaped = last_scaled.reshape(1, n_lags, 1)
        else:
            last_reshaped = last_scaled

        pred_scaled = model.predict(last_reshaped, verbose=0)

        if pred_scaled.ndim > 1:
            pred_scaled = pred_scaled[0, 0]
        else:
            pred_scaled = pred_scaled[0]

        pred = scaler_y.inverse_transform([[pred_scaled]])[0, 0]

        forecasts.append(pred)
        models.append(model)
        histories.append(history)

    return np.array(forecasts), models, histories

# 4. УНИВЕРСАЛЬНАЯ ФУНКЦИЯ ДЛЯ ВСЕХ МЕТОДОВ
def neural_network_forecast(series, n_steps, method='direct', model_type='lstm',
                           n_lags=20, units=50, epochs=100, batch_size=32, activator='relu', losses='mse', **kwargs):
    """
    Универсальная функция для нейросетевого прогнозирования
    """

    # Проверка достаточности данных
    if len(series) < n_lags + n_steps:
        raise ValueError(f"Недостаточно данных. Нужно минимум {n_lags + n_steps} точек, есть {len(series)}")

    if method == 'direct':
        result = direct_output_nn(series, n_steps, n_lags, model_type, units, epochs, batch_size, activator, losses, **kwargs)
        return result[0], result[1], result[2]  # forecast, model, history

    elif method == 'recursive':
        result = recursive_nn_forecast(series, n_steps, n_lags, model_type, units, epochs, batch_size, activator, losses, **kwargs)
        return result[0], result[1], result[2]  # forecast, model, history

    elif method == 'individual':
        result = individual_models_nn(series, n_steps, n_lags, model_type, units, epochs, batch_size, activator, losses, **kwargs)
        return result[0], result[1], result[2]  # forecast, models, histories

    else:
        raise ValueError("Метод должен быть 'direct', 'recursive' или 'individual'")

