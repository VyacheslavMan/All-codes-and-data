def optuna_prog(data, forecast_horizon, err_type, need_optuna, n_trials):

    def objective(trial, data=data
                  , forecast_horizon=forecast_horizon, err_type=err_type):


        params = {

                'changepoint_prior_scale': trial.suggest_float('changepoint_prior_scale', 0.001, 0.5),
                'seasonality_prior_scale': trial.suggest_float('seasonality_prior_scale', 0.01, 10),
                'holidays_prior_scale': trial.suggest_float('holidays_prior_scale', 0.01, 10),
                'seasonality_mode': trial.suggest_categorical('seasonality_mode', ['additive', 'multiplicative']),
                'n_changepoints': trial.suggest_int('n_changepoints', 5, 50),
                'changepoint_range': trial.suggest_float('changepoint_range', 0.8, 0.95),
                'yearly_seasonality': trial.suggest_categorical('yearly_seasonality', [True, False, 5, 10, 15]),
                'weekly_seasonality': trial.suggest_categorical('weekly_seasonality', [True, False, 3, 5]),
                'daily_seasonality': trial.suggest_categorical('daily_seasonality', [True, False, 5, 10, 15]),
                # 'uncertainty_samples':trial.suggest_int('uncertainty_samples', 500, 3000, step=100),
                # 'mcmc_samples': trial.suggest_int('mcmc_samples', 0, 200, step=20)
            }

        model = Prophet(**params)
        model.fit(data[:-forecast_horizon])

        future = model.make_future_dataframe(periods=forecast_horizon)
        forecast = model.predict(future)

        test=data[-forecast_horizon:]
        prognoz=forecast['yhat'][-forecast_horizon:]

        t1=all_errs_toch_interval(np.array(test['y']), prognoz)


        # metr=0

        if err_type=='smape_tochech':
            metr=np.array(t1[0]).mean()
        elif err_type=='smape_interv':
            metr=np.array(t1[1]).mean()
        elif err_type=='mape_tochech':
            metr=np.array(t1[2]).mean()
        elif err_type=='mape_interv':
            metr=np.array(t1[3]).mean()
        else:
            metr=0

        return metr

    if need_optuna==1:

        study = optuna.create_study(direction='minimize', sampler=TPESampler(seed=42))
        study.optimize(objective, n_trials=n_trials, n_jobs=-1, show_progress_bar=False)

        best_params = study.best_params
        final_model = Prophet(**best_params)
    else:
        final_model = Prophet()

    final_model.fit(data)

    future = final_model.make_future_dataframe(periods=forecast_horizon)
    forecast = final_model.predict(future)

    prognoz=np.array(forecast['yhat'][-forecast_horizon:])

    return prognoz

