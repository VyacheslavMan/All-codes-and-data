def svod_mape(fr, name_col):
    frr=pd.DataFrame()
    for j in range(0,len(fr)):

        hor=[]
        mape=[]

        mapes=100*abs(np.array(fr.prog[j])-np.array(fr.toch[j]))/np.array(fr.prog[j])

        for i in range(1,len(fr.prog[0])):

            hor.append(i)
            mape.append(float(mapes[0:i].mean()))

        frr[fr.date[j]]=mape

    frr=pd.DataFrame(frr.T.mean())
    frr['horizont']=hor
    frr = frr.rename(columns={frr.columns[0]: name_col})
    return frr

def smape_array(y_true, y_pred):
    y_true = np.array(y_true, dtype=float)
    y_pred = np.array(y_pred, dtype=float)
    denom = (np.abs(y_true) + np.abs(y_pred)) / 2.0
    diff = np.abs(y_true - y_pred)
    mask = denom != 0
    if mask.sum() == 0:
        return np.nan
    return np.mean(diff[mask] / denom[mask]) * 100

def mape_array(y_true, y_pred):
    y_true = np.array(y_true, dtype=float)
    y_pred = np.array(y_pred, dtype=float)
    mapes=100*abs(y_pred-y_true)/y_true

    return np.mean(mapes)

"""Сводные погрешности"""

def all_errs_toch_interval(y_true, y_pred):

    smape_tochech=[]
    smape_interv=[]

    mape_tochech=[]
    mape_interv=[]

    for i in range(1, len(y_true)):
        smape_tochech.append(smape_array(y_true[i-1:i], y_pred[i-1:i]))
        smape_interv.append(smape_array(y_true[0:i], y_pred[0:i]))

        mape_tochech.append(mape_array(y_true[i-1:i], y_pred[i-1:i]))
        mape_interv.append(mape_array(y_true[0:i], y_pred[0:i]))

    return smape_tochech, smape_interv, mape_tochech, mape_interv

