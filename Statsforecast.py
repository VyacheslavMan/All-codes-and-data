def statsforecast_alls(data, horizont, modelos):

    sf = StatsForecast(
            models=modelos,
            freq='D',
            n_jobs=-1
        )

    # # Обучаем модели на данных
    sf.fit(df=data)

    # # Прогнозируем
    forecast = sf.predict(h=horizont)
    return forecast


