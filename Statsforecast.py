import pandas as pd
from datetime import datetime
def create_date_series(start, periods, freq='D', date_format=None):
    """
    Создает список дат с различными опциями

    Parameters:
    -----------
    start : str или datetime
        Начальная дата
    periods : int
        Количество периодов
    freq : str
        Частота: 'D' - день, 'W' - неделя, 'M' - месяц, 'Q' - квартал, 'Y' - год
        Также можно использовать: '2D' - каждые 2 дня, 'W-MON' - каждый понедельник
    date_format : str, optional
        Формат вывода дат (например, '%Y-%m-%d')

    Returns:
    --------
    list или DatetimeIndex
    """
    dates = pd.date_range(start=start, periods=periods, freq=freq)

    if date_format:
        dates = [d.strftime(date_format) for d in dates]

    return dates

